int main(void)
{
    CFDataRef valid = CFDataCreate(kCFAllocatorDefault, kValidSbixFont, (CFIndex)sizeof kValidSbixFont);
    CFDataRef crafted = CFDataCreate(kCFAllocatorDefault, kCraftedSbixFont, (CFIndex)sizeof kCraftedSbixFont);

    CFDataRef sanitizedValid = wk_ots_sanitize_font(valid);
    check(sanitizedValid != NULL, "a sound sbix font is accepted");
    check(sanitizedValid && hasSbixTable(sanitizedValid), "the accepted font keeps its sbix table");

    CFDataRef sanitizedCrafted = wk_ots_sanitize_font(crafted);
    check(sanitizedCrafted == NULL, "an sbix font with an out-of-bounds record offset is refused");

    if (sanitizedValid)
        CFRelease(sanitizedValid);
    if (sanitizedCrafted)
        CFRelease(sanitizedCrafted);
    CFRelease(valid);
    CFRelease(crafted);

    CFDataRef dupeShort = CFDataCreate(kCFAllocatorDefault, kSbixDupeShort, (CFIndex)sizeof kSbixDupeShort);
    check(wk_ots_sanitize_font(dupeShort) == NULL, "an sbix 'dupe' record shorter than 10 bytes is refused");
    CFRelease(dupeShort);

    CFDataRef dupeOOB = CFDataCreate(kCFAllocatorDefault, kSbixDupeTargetOOB, (CFIndex)sizeof kSbixDupeTargetOOB);
    check(wk_ots_sanitize_font(dupeOOB) == NULL, "an sbix 'dupe' whose target glyph is past the glyph count is refused");
    CFRelease(dupeOOB);

    CFDataRef dupeValid = CFDataCreate(kCFAllocatorDefault, kSbixDupeValid, (CFIndex)sizeof kSbixDupeValid);
    CFDataRef sanitizedDupeValid = wk_ots_sanitize_font(dupeValid);
    check(sanitizedDupeValid != NULL, "a sound sbix 'dupe' record is accepted");
    check(sanitizedDupeValid && hasSbixTable(sanitizedDupeValid), "the accepted 'dupe' font keeps its sbix table");
    if (sanitizedDupeValid)
        CFRelease(sanitizedDupeValid);
    CFRelease(dupeValid);

    if (failures) {
        printf("CoreText-sbix-sanitizer: %d FAILED\n", failures);
        return 1;
    }
    printf("CoreText-sbix-sanitizer: ok\n");
    return 0;
}
