// The sbix bounds check in wk_ots_sanitize_font (polyfills/c/ots_font_parser.cpp). OTS models no sbix
// table and the parser passes it through, so a downloaded font's colour-bitmap offsets reach CoreText
// as the font supplied them. This OS follows a glyph's record offset without checking it lies inside
// the table, and CTFontDrawGlyphs and CTFontCreatePathForGlyph fault on one that points past the end.
// The sanitizer answers NULL for a font whose in-range sbix offsets run outside the table, and keeps
// one whose offsets are sound -- with its sbix table intact, so downloadable colour glyphs still draw.
//
// The two fixtures are one outline+sbix font: kValidSbixFont as built, and kCraftedSbixFont with an
// in-range glyph's record start offset moved past the table end. The probe links libpolyfill.a, so
// wk_ots_sanitize_font is the archive's.
#include <CoreFoundation/CoreFoundation.h>
#include <stdio.h>

extern CFDataRef wk_ots_sanitize_font(CFDataRef data);

static int failures;
static void check(int ok, const char *what)
{
    printf("  %-64s %s\n", what, ok ? "ok" : "FAIL");
    if (!ok)
        failures++;
}

static int hasSbixTable(CFDataRef font)
{
    const UInt8 *p = CFDataGetBytePtr(font);
    CFIndex n = CFDataGetLength(font);
    if (n < 12)
        return 0;
    unsigned tables = (p[4] << 8) | p[5];
    if (12 + (CFIndex)tables * 16 > n)
        return 0;
    for (unsigned i = 0; i < tables; ++i) {
        const UInt8 *r = p + 12 + i * 16;
        if (r[0] == 's' && r[1] == 'b' && r[2] == 'i' && r[3] == 'x')
            return 1;
    }
    return 0;
}

