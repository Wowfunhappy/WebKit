// 10.9's own definition, read off Security's image: the layer's dlsym answers with its replacement.
static void *stockSymbol(const char *name)
{
    for (uint32_t i = 0; i < _dyld_image_count(); ++i) {
        if (!strstr(_dyld_get_image_name(i), "/Security.framework/"))
            continue;
        NSSymbol symbol = NSLookupSymbolInImage(_dyld_get_image_header(i), name,
            NSLOOKUPSYMBOLINIMAGE_OPTION_BIND | NSLOOKUPSYMBOLINIMAGE_OPTION_RETURN_ON_ERROR);
        return symbol ? NSAddressOfSymbol(symbol) : NULL;
    }
    return NULL;
}

typedef OSStatus (*CopyPoliciesFunction)(SecTrustRef, CFArrayRef *);
typedef OSStatus (*GetTrustResultFunction)(SecTrustRef, SecTrustResultType *);

struct Race {
    SecTrustRef trust;
    int refused;
};

static void *evaluateRepeatedly(void *context)
{
    struct Race *race = context;
    for (int i = 0; i < 1000; ++i) {
        SecTrustResultType result = kSecTrustResultInvalid;
        SecTrustEvaluate(race->trust, &result);
        if (result == kSecTrustResultRecoverableTrustFailure)
            race->refused++;
    }
    return NULL;
}

static int failures;
static void check(int ok, const char *what)
{
    printf("  %-84s %s\n", what, ok ? "ok" : "FAIL");
    if (!ok)
        failures++;
}

static bool accepted(SecTrustResultType result)
{
    return result == kSecTrustResultProceed || result == kSecTrustResultUnspecified;
}

int main(void)
{
    CFArrayRef anchors = NULL;
    SecTrustCopyAnchorCertificates(&anchors);
    if (!anchors || !CFArrayGetCount(anchors)) {
        printf("Security-trust-state-lifetime: no system anchors\n");
        return 1;
    }
    const void *anchor = CFArrayGetValueAtIndex(anchors, 0);
    CFArrayRef certificates = CFArrayCreate(NULL, &anchor, 1, &kCFTypeArrayCallBacks);
    SecPolicyRef basic = SecPolicyCreateBasicX509();
    SecPolicyRef wrongHost = SecPolicyCreateSSL(true, CFSTR("host-the-anchor-does-not-name.invalid"));

    int reused = 0, refusedAtReusedAddress = 0, acceptedFirst = 0;
    const int rounds = 200;
    for (int i = 0; i < rounds; ++i) {
        SecTrustRef first = NULL;
        SecTrustCreateWithCertificates(certificates, basic, &first);
        SecTrustResultType result = kSecTrustResultInvalid;
        SecTrustEvaluate(first, &result);
        if (accepted(result))
            acceptedFirst++;
        const void *address = first;
        CFRelease(first);

        SecTrustRef second = NULL;
        SecTrustCreateWithCertificates(certificates, wrongHost, &second);
        result = kSecTrustResultInvalid;
        SecTrustEvaluate(second, &result);
        if ((const void *)second == address) {
            reused++;
            if (!accepted(result))
                refusedAtReusedAddress++;
        }
        CFRelease(second);
    }
    char what[128];
    snprintf(what, sizeof what, "the anchor evaluated as itself is accepted (%d/%d)", acceptedFirst, rounds);
    check(acceptedFirst == rounds, what);
    snprintf(what, sizeof what, "new trusts landed where an accepted one lived (%d/%d)", reused, rounds);
    check(reused > 0, what);
    snprintf(what, sizeof what, "each of those evaluated for itself and was refused (%d/%d)", refusedAtReusedAddress, reused);
    check(refusedAtReusedAddress == reused, what);

    // SecTrustCopyPolicies hands back the caller's policies, as a copy that stays the caller's after the
    // trust changes.
    SecTrustRef trust = NULL;
    SecTrustCreateWithCertificates(certificates, wrongHost, &trust);
    SecTrustResultType result;
    SecTrustEvaluate(trust, &result);
    CFArrayRef policies = NULL;
    SecTrustCopyPolicies(trust, &policies);
    check(policies && CFArrayGetCount(policies) == 1 && CFArrayGetValueAtIndex(policies, 0) == wrongHost,
        "SecTrustCopyPolicies after an evaluation reports exactly the caller's policy");
    CFArrayRef again = NULL;
    SecTrustCopyPolicies(trust, &again);
    check(policies && again && policies != again, "each SecTrustCopyPolicies call hands back the caller's own array");

    // What a setter was given survives a change of policies, and so reaches the serialized trust.
    SecTrustSetOptions(trust, kSecTrustOptionAllowExpired);
    SecTrustSetPolicies(trust, basic);
    CFDataRef blob = SecTrustSerialize(trust, NULL);
    CFDictionaryRef state = blob ? (CFDictionaryRef)CFPropertyListCreateWithData(NULL, blob, kCFPropertyListImmutable, NULL, NULL) : NULL;
    CFDictionaryRef settings = state ? (CFDictionaryRef)CFDictionaryGetValue(state, CFSTR("settings")) : NULL;
    CFNumberRef options = settings ? (CFNumberRef)CFDictionaryGetValue(settings, CFSTR("options")) : NULL;
    int64_t value = 0;
    check(options && CFNumberGetValue(options, kCFNumberSInt64Type, &value) && value == kSecTrustOptionAllowExpired,
        "SecTrustSetOptions's value survives SecTrustSetPolicies into the serialized trust");
    result = kSecTrustResultInvalid;
    SecTrustEvaluate(trust, &result);
    check(accepted(result), "after SecTrustSetPolicies the trust evaluates under the new policy");

    // 10.9's own SecTrustCopyPolicies and SecTrustGetTrustResult, not the polyfill's.
    CopyPoliciesFunction stockCopyPolicies = (CopyPoliciesFunction)stockSymbol("_SecTrustCopyPolicies");
    GetTrustResultFunction stockGetTrustResult = (GetTrustResultFunction)stockSymbol("_SecTrustGetTrustResult");
    check(stockCopyPolicies && (void *)stockCopyPolicies != (void *)SecTrustCopyPolicies && stockGetTrustResult,
        "10.9's own SecTrustCopyPolicies and SecTrustGetTrustResult are reachable");

    SecTrustRef refused = NULL;
    SecTrustCreateWithCertificates(certificates, wrongHost, &refused);
    result = kSecTrustResultInvalid;
    SecTrustEvaluate(refused, &result);
    CFArrayRef stock = NULL;
    stockCopyPolicies(refused, &stock);
    check(stock && CFArrayGetCount(stock) == 1 && CFArrayGetValueAtIndex(stock, 0) == wrongHost,
        "after an evaluation 10.9's own SecTrustCopyPolicies reports exactly the caller's policy");
    SecTrustResultType native = kSecTrustResultInvalid;
    stockGetTrustResult(refused, &native);
    check(native == result, "10.9's own evaluation result survives the state array installed before it");
    OSStatus code = 0;
    SecTrustGetCssmResultCode(refused, &code);
    SecTrustResultType nativeAfter = kSecTrustResultInvalid;
    stockGetTrustResult(refused, &nativeAfter);
    check(nativeAfter == native, "a CSSM accessor reads that result rather than evaluating again");
    if (stock)
        CFRelease(stock);
    CFRelease(refused);

    // The array 10.9 hands out for an accepted trust, given to a trust over an untrusted certificate.
    SecTrustRef acceptedTrust = NULL;
    SecTrustCreateWithCertificates(certificates, basic, &acceptedTrust);
    result = kSecTrustResultInvalid;
    SecTrustEvaluate(acceptedTrust, &result);
    CFArrayRef handedOut = NULL;
    stockCopyPolicies(acceptedTrust, &handedOut);
    CFDataRef selfSignedData = CFDataCreate(NULL, selfSigned, sizeof(selfSigned));
    SecCertificateRef selfSignedCertificate = SecCertificateCreateWithData(NULL, selfSignedData);
    SecTrustRef foreign = NULL;
    SecTrustCreateWithCertificates(selfSignedCertificate, handedOut, &foreign);
    SecTrustResultType foreignResult = kSecTrustResultInvalid;
    SecTrustEvaluate(foreign, &foreignResult);
    check(accepted(result) && foreignResult == kSecTrustResultRecoverableTrustFailure,
        "a trust given another trust's policies array evaluates for itself");
    result = kSecTrustResultInvalid;
    SecTrustEvaluate(acceptedTrust, &result);
    check(accepted(result), "and the trust the array came from still answers for itself");
    CFRelease(foreign);
    CFRelease(selfSignedCertificate);
    CFRelease(selfSignedData);
    if (handedOut)
        CFRelease(handedOut);
    CFRelease(acceptedTrust);

    // 10.9 creates a trust from an empty array; with no input certificates it has no identity a holder
    // can check, so it carries no state: the trust keeps the caller's own policies array.
    CFArrayRef emptyCertificates = CFArrayCreate(NULL, NULL, 0, &kCFTypeArrayCallBacks);
    const void *basicPolicy = basic;
    CFArrayRef callersPolicies = CFArrayCreate(NULL, &basicPolicy, 1, &kCFTypeArrayCallBacks);
    SecTrustRef empty = NULL;
    SecTrustCreateWithCertificates(emptyCertificates, callersPolicies, &empty);
    if (empty) {
        result = kSecTrustResultInvalid;
        SecTrustEvaluate(empty, &result);
        SecTrustSetOptions(empty, kSecTrustOptionAllowExpired);
        SecTrustEvaluate(empty, &result);
        CFArrayRef held = NULL;
        stockCopyPolicies(empty, &held);
        check(held == callersPolicies, "a trust with no input certificates keeps no state beside it");
        CFDataRef emptyBlob = SecTrustSerialize(empty, NULL);
        check(!emptyBlob, "and is not serialized");
        if (emptyBlob)
            CFRelease(emptyBlob);
        if (held)
            CFRelease(held);
        CFRelease(empty);
    } else
        check(false, "10.9 creates a trust from an empty certificate array");
    CFRelease(callersPolicies);
    CFRelease(emptyCertificates);

    // Evaluations on one thread, setters that discard them on another.
    struct Race race = { NULL, 0 };
    SecTrustCreateWithCertificates(certificates, wrongHost, &race.trust);
    pthread_t evaluator;
    pthread_create(&evaluator, NULL, evaluateRepeatedly, &race);
    for (int i = 0; i < 1000; ++i)
        SecTrustSetOptions(race.trust, (i & 1) ? kSecTrustOptionAllowExpired : 0);
    pthread_join(evaluator, NULL);
    snprintf(what, sizeof what, "evaluations racing SecTrustSetOptions all refused the wrong host (%d/1000)", race.refused);
    check(race.refused == 1000, what);
    CFRelease(race.trust);

    if (state)
        CFRelease(state);
    if (blob)
        CFRelease(blob);
    if (again)
        CFRelease(again);
    if (policies)
        CFRelease(policies);
    CFRelease(trust);
    CFRelease(wrongHost);
    CFRelease(basic);
    CFRelease(certificates);
    CFRelease(anchors);
    return failures ? 1 : 0;
}
